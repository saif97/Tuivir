#!/usr/bin/env python3
"""Exercise release commands against disposable repositories and artifacts."""

import json
import copy
import subprocess
import tempfile
import unittest
from pathlib import Path


SCRIPT = Path(__file__).resolve().parents[1] / "scripts/release.py"
MANIFEST = '''[package]
name = "tuivir"
version = "0.2.7"
edition = "2024"

[dependencies]
example = "0.2.7"
'''
LOCKFILE = '''# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "example"
version = "0.2.7"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "tuivir"
version = "0.2.7"
dependencies = ["example"]
'''


class ReleaseCommands(unittest.TestCase):
    def setUp(self):
        self.directory = tempfile.TemporaryDirectory()
        self.addCleanup(self.directory.cleanup)
        self.root = Path(self.directory.name)
        (self.root / "Cargo.toml").write_text(MANIFEST)
        (self.root / "Cargo.lock").write_text(LOCKFILE)
        self.git("init", "-b", "master")
        self.git("config", "user.name", "Release test")
        self.git("config", "user.email", "release@example.invalid")
        self.commit("Initial source")

    def git(self, *args):
        return subprocess.check_output(
            ["git", *args], cwd=self.root, text=True, stderr=subprocess.PIPE
        ).strip()

    def commit(self, message):
        self.git("add", ".")
        self.git("commit", "-m", message)
        return self.git("rev-parse", "HEAD")

    def release(self, *args, success=True):
        result = subprocess.run(
            ["python3", str(SCRIPT), *args], cwd=self.root,
            text=True, capture_output=True,
        )
        if success:
            self.assertEqual(result.returncode, 0, result.stderr)
        else:
            self.assertNotEqual(result.returncode, 0, result.stdout)
        return result

    def test_minor_bump_updates_package_and_lock_without_changing_dependencies(self):
        result = self.release("bump", "minor")
        self.assertEqual(result.stdout.strip(), "0.3.0")
        self.assertEqual((self.root / "Cargo.toml").read_text(), '''[package]
name = "tuivir"
version = "0.3.0"
edition = "2024"

[dependencies]
example = "0.2.7"
''')
        self.assertEqual((self.root / "Cargo.lock").read_text(), '''# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "example"
version = "0.2.7"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "tuivir"
version = "0.3.0"
dependencies = ["example"]
''')

    def release_event(self):
        self.release("bump", "minor")
        commit = self.commit("Release v0.3.0")
        event = {
            "repository": {"full_name": "saif97/Tuivir", "default_branch": "master"},
            "pull_request": {
                "merged": True,
                "merge_commit_sha": commit,
                "base": {"ref": "master", "repo": {"full_name": "saif97/Tuivir"}},
                "head": {"ref": "release/v0.3.0", "repo": {"full_name": "saif97/Tuivir"}},
            },
        }
        return event

    def check_event(self, event, success=True):
        path = self.root / "event.json"
        path.write_text(json.dumps(event))
        return self.release("merged-tag", str(path), "--repo", "saif97/Tuivir", success=success)

    def test_merged_release_uses_merge_commit_even_when_master_has_advanced(self):
        event = self.release_event()
        (self.root / "README.md").write_text("A later change\n")
        self.commit("Another PR")
        self.git("update-ref", "refs/remotes/origin/master", "HEAD")
        result = json.loads(self.check_event(event).stdout)
        self.assertEqual(result, {
            "tag": "v0.3.0", "version": "0.3.0",
            "commit": event["pull_request"]["merge_commit_sha"],
        })

    def test_release_pr_cannot_smuggle_source_changes_into_automatic_tagging(self):
        event = self.release_event()
        (self.root / "source.rs").write_text("unreviewed release machinery\n")
        self.git("add", "source.rs")
        self.git("commit", "--amend", "--no-edit")
        event["pull_request"]["merge_commit_sha"] = self.git("rev-parse", "HEAD")
        self.git("update-ref", "refs/remotes/origin/master", "HEAD")
        self.check_event(event, success=False)

    def remote(self):
        directory = tempfile.TemporaryDirectory()
        self.addCleanup(directory.cleanup)
        subprocess.run(["git", "init", "--bare", directory.name],
                       check=True, capture_output=True)
        self.git("remote", "add", "origin", directory.name)
        self.git("push", "origin", "master")
        return directory.name

    def test_tag_creation_can_be_retried_without_moving_the_remote_tag(self):
        self.remote()
        commit = self.git("rev-parse", "HEAD")
        self.release("tag", "v0.2.7", commit)
        first = self.git("ls-remote", "--tags", "origin")
        self.release("tag", "v0.2.7", commit)
        self.assertEqual(self.git("ls-remote", "--tags", "origin"), first)
        self.assertIn(commit + "\trefs/tags/v0.2.7^{}", first)

    def test_existing_remote_tag_is_never_replaced_with_another_commit(self):
        self.remote()
        self.release("tag", "v0.2.7", self.git("rev-parse", "HEAD"))
        original = self.git("ls-remote", "--tags", "origin")
        (self.root / "README.md").write_text("Different source, same version\n")
        other = self.commit("Different commit")
        self.release("tag", "v0.2.7", other, success=False)
        self.assertEqual(self.git("ls-remote", "--tags", "origin"), original)

    def test_patch_and_major_bumps(self):
        for kind, expected in (("patch", "0.2.8"), ("major", "1.0.0")):
            with self.subTest(kind=kind):
                self.git("restore", "Cargo.toml", "Cargo.lock")
                self.assertEqual(self.release("bump", kind).stdout.strip(), expected)

    def test_invalid_bump_or_inconsistent_lock_does_not_modify_files(self):
        self.release("bump", "automatic", success=False)
        self.assertEqual((self.root / "Cargo.toml").read_text(), MANIFEST)
        lock = LOCKFILE.replace('name = "tuivir"\nversion = "0.2.7"',
                                'name = "tuivir"\nversion = "0.2.6"')
        (self.root / "Cargo.lock").write_text(lock)
        self.release("bump", "minor", success=False)
        self.assertEqual((self.root / "Cargo.toml").read_text(), MANIFEST)
        self.assertEqual((self.root / "Cargo.lock").read_text(), lock)

    def test_unmerged_fork_wrong_branch_and_invalid_commit_cannot_release(self):
        original = self.release_event()
        self.git("update-ref", "refs/remotes/origin/master", "HEAD")
        for field, value in (("merged", False), ("merge_commit_sha", "--help"),
                             ("head", {"ref": "release/v0.3.0", "repo": {"full_name": "other/fork"}}),
                             ("head", {"ref": "feature/test", "repo": {"full_name": "saif97/Tuivir"}}),
                             ("base", {"ref": "other", "repo": {"full_name": "saif97/Tuivir"}})):
            with self.subTest(field=field, value=value):
                event = copy.deepcopy(original)
                event["pull_request"][field] = value
                self.check_event(event, success=False)

    def test_dependency_changes_inside_cargo_files_cannot_release(self):
        event = self.release_event()
        path = self.root / "Cargo.toml"
        path.write_text(path.read_text().replace('example = "0.2.7"', 'example = "9.0.0"'))
        self.git("add", "Cargo.toml")
        self.git("commit", "--amend", "--no-edit")
        event["pull_request"]["merge_commit_sha"] = self.git("rev-parse", "HEAD")
        self.git("update-ref", "refs/remotes/origin/master", "HEAD")
        self.check_event(event, success=False)


if __name__ == "__main__":
    unittest.main()
